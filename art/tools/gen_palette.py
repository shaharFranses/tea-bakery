"""Generate a Godot ArtPalette script + palette.json from ttcolor.py.
Adapted from Sudoku Dash tools/art/gen_palette.py @a795a1a (PKD in-house). Change: generates the
whole .gd file (SD regex-patched an existing one), and adds region colours + pattern names."""
import os, ttcolor as T
OUT=os.path.join(os.path.dirname(__file__),"out"); os.makedirs(OUT,exist_ok=True)
T.export_palette_json(os.path.join(OUT,"palette.json"))
L=["## tea-bakery (game #4) art palette. GENERATED by art/tools/gen_palette.py from ttcolor.py; do not hand-edit.",
   "## PROPOSED (pending Shahar's approval). Pure constants, no side effects.","class_name ArtPalette","extends RefCounted",""]
for n,h,use in T.UI: L.append(f'const {n.upper()} := Color("{h.lstrip("#")}")  # {use}')
L.append("")
L.append("## Dough-patch regions: index = region id. Never colour-only: pair with REGION_PATTERNS[i].")
L.append("const REGION_COLORS: Array[Color] = ["+", ".join(f'Color("{h.lstrip("#")}")' for _,h,_ in T.REGIONS)+"]")
L.append("const REGION_NAMES: Array[String] = ["+", ".join(f'"{n}"' for n,_,_ in T.REGIONS)+"]")
L.append("const REGION_PATTERNS: Array[String] = ["+", ".join(f'"{p}"' for _,_,p in T.REGIONS)+"]")
open(os.path.join(OUT,"art_palette.gd"),"w").write("\n".join(L)+"\n")
rows=T.contrast_table()
for r in rows: print("| %s | %s | %.2f:1 | %.1f | %s |"%r)
print("FAILS:",[r for r in rows if r[4]=="FAIL"])
