"""Generate a Godot ArtPalette script + palette.json from ttcolor.py.
Adapted from Sudoku Dash tools/art/gen_palette.py @a795a1a (PKD in-house). Change: generates the
whole .gd file (SD regex-patched an existing one), and adds region colours + pattern names."""
import os, ttcolor as T
OUT=os.path.join(os.path.dirname(__file__),"out"); os.makedirs(OUT,exist_ok=True)
T.export_palette_json(os.path.join(OUT,"palette.json"))
L=["## tea-bakery (game #4) art palette. GENERATED by art/tools/gen_palette.py from ttcolor.py; do not hand-edit.",
   "## APPROVED style B2 (2026-10-25). SPEC v1.0.1 sec. 10. Pure constants, no side effects.","class_name ArtPalette","extends RefCounted",""]
for n,h,use in T.UI: L.append(f'const {n.upper()} := Color("{h.lstrip("#")}")  # {use}')
L.append("")
L.append("## Dough-patch regions: index = region id. Never colour-only: pair with REGION_PATTERNS[i].")
L.append("const REGION_COLORS: Array[Color] = ["+", ".join(f'Color("{h.lstrip("#")}")' for _,h,_ in T.REGIONS)+"]")
L.append("const REGION_NAMES: Array[String] = ["+", ".join(f'"{n}"' for n,_,_ in T.REGIONS)+"]")
L.append("const REGION_PATTERNS: Array[String] = ["+", ".join(f'"{p}"' for _,_,p in T.REGIONS)+"]")
def _hx(h,f): c=[int(h[i:i+2],16) for i in (1,3,5)]; return "%02X%02X%02X"%tuple(int(min(255,x*f)) for x in c)
L.append("const REGION_SEAMS: Array[Color] = ["+", ".join(f'Color("{_hx(h,0.93)}")' for _,h,_ in T.REGIONS)+"]  # same-region join (0.93x fill)")
L.append("const REGION_RIMS: Array[Color] = ["+", ".join(f'Color("{_hx(h,0.72)}")' for _,h,_ in T.REGIONS)+"]  # soft region rim (0.72x fill)")
L += ["", "## Board geometry (fractions of cell pitch) and extra board colours",
  'const TRAY_LINING := Color("FFF8EC")  # gap between different regions',
  'const HINT_GOLD := Color("F2C14E")  # hint unit glow / target ring',
  'const SOLVED_TRAY_TINT := Color(0.788, 0.502, 0.227, 0.22)  # toasted crust over the board when solved',
  'const SCRIM := Color(0.263, 0.157, 0.227, 0.45)  # modal backdrop (ink at 45%)',
  "const TILE_GAP := 0.075", "const TILE_RADIUS := 0.22", "const RIM_WIDTH := 0.06",
  "const MOLD_DRAW := 0.70", "const CAKE_DRAW := 1.0"]
for d in (OUT, "/workspace/tea-and-tarts/ui/theme"):
    os.makedirs(d,exist_ok=True); open(os.path.join(d,"art_palette.gd"),"w").write("\n".join(L)+"\n")
